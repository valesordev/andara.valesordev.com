// TestFormatIsIdempotent is AC-3 and formatting.md AC-1: a second run of fmt
// changes nothing, over every .aw in the corpus.
func TestFormatIsIdempotent(t *testing.T) {
	for _, path := range corpusSources(t) {
		src, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		once, ds := Format(src)
		if len(ds) > 0 {
			if strings.Contains(path, "invalid/syntax") || strings.Contains(path, "invalid/encoding") {
				continue // these do not parse, by construction
			}
			t.Errorf("%s: %v", path, ds[0])
			continue
		}
		twice, ds := Format(once)
		if len(ds) > 0 {
			t.Errorf("%s: formatted output does not re-parse: %v", path, ds[0])
			continue
		}
		if string(once) != string(twice) {
			t.Errorf("%s: fmt is not idempotent:\n--- once ---\n%s\n--- twice ---\n%s", path, once, twice)
		}
	}
}

// TestCorpusIsFormatted is formatting.md AC-2: every .aw a Builder would read
// is already fmt-clean, so `content fmt --check` over the corpus exits 0.
func TestCorpusIsFormatted(t *testing.T) {
	for _, path := range corpusSources(t) {
		if strings.Contains(path, "invalid/syntax") || strings.Contains(path, "invalid/encoding") {
			continue
		}
		src, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		got, ds := Format(src)
		if len(ds) > 0 {
			t.Errorf("%s: %v", path, ds[0])
			continue
		}
		if string(got) != string(src) {
			t.Errorf("%s is not fmt-clean:\n--- want ---\n%s\n--- got ---\n%s", path, src, got)
		}
	}
}

// TestFormatDoesNotReorder is formatting.md AC-4, the load-bearing decision in
// that document. A Builder who lays out a Zone as the walk through it keeps
// that layout, and the compiled output is sorted regardless.
func TestFormatDoesNotReorder(t *testing.T) {
	src := []byte(`zone z "Z" {
  room plaza "Plaza" {
    exit north -> lane
    exit east -> alley
  }

  room lane "Lane" {
    exit south -> plaza
  }

  room alley "Alley" {
    exit west -> plaza
  }
}
`)
	got, ds := Format(src)
	if len(ds) > 0 {
		t.Fatal(ds[0])
	}
	if string(got) != string(src) {
		t.Errorf("fmt reordered a Zone:\n--- want ---\n%s\n--- got ---\n%s", src, got)
	}
	// ... and the compiled output is sorted regardless.
	dir := t.TempDir()
	write(t, filepath.Join(dir, "pack.aw"), "pack p requires andara.core@1\n")
	write(t, filepath.Join(dir, "z.aw"), string(src))
	out, ds := Compile(dir, corpusCore(t), nil)
	if out == nil {
		t.Fatalf("compile: %v", ds)
	}
	rooms := out.Zones[0].GetRooms()
	if rooms[0].GetId() != "alley" || rooms[1].GetId() != "lane" || rooms[2].GetId() != "plaza" {
		t.Errorf("compiled Rooms are not sorted by id: %s, %s, %s", rooms[0].GetId(), rooms[1].GetId(), rooms[2].GetId())
	}
	exits := rooms[2].GetExits()
	if exits[0].GetDirection() != "east" || exits[1].GetDirection() != "north" {
		t.Errorf("compiled Exits are not sorted by direction string: %s, %s", exits[0].GetDirection(), exits[1].GetDirection())
	}
}

// TestCompileIsOrderIndependent is semantics.md §2: neither the order of files
// in a pack nor the order of declarations within a file affects the compiled
// output.
func TestCompileIsOrderIndependent(t *testing.T) {
	one := t.TempDir()
	write(t, filepath.Join(one, "pack.aw"), "pack p requires andara.core@1\n")
	write(t, filepath.Join(one, "a.aw"), "template Wolf extends Beast {}\n")
	write(t, filepath.Join(one, "b.aw"), "template Beast kind entity {}\n")

	two := t.TempDir()
	write(t, filepath.Join(two, "pack.aw"), "pack p requires andara.core@1\n")
	write(t, filepath.Join(two, "z.aw"), "template Beast kind entity {}\ntemplate Wolf extends Beast {}\n")

	a, ds := Compile(one, corpusCore(t), nil)
	if a == nil {
		t.Fatalf("compile: %v", ds)
	}
	b, ds := Compile(two, corpusCore(t), nil)
	if b == nil {
		t.Fatalf("compile: %v", ds)
	}
	for i := range a.Templates {
		// Names differ by temp directory, so compare the parts that should not.
		ja := string(CanonicalJSON(a.Templates[i]))
		jb := string(CanonicalJSON(b.Templates[i]))
		// SourceRef legitimately differs — different files, different lines.
		ja, jb = stripSource(ja), stripSource(jb)
		if ja != jb {
			t.Errorf("declaration order changed the output:\n--- a ---\n%s\n--- b ---\n%s", ja, jb)
		}
	}
}

func stripSource(s string) string {
	i := strings.Index(s, `"source"`)
	if i < 0 {
		return s
	}
	return s[:i]
}

// TestOfflineCompileUsesTheCache is AC-5: a cached andara.core@1 compiles with
// no network, and no cache at all is core_version_mismatch telling the Builder
// to run `content fetch-core` rather than a missing-file error.
func TestOfflineCompileUsesTheCache(t *testing.T) {
	core := corpusCore(t)
	root := t.TempDir()
	if err := WriteCachedPack(root, core); err != nil {
		t.Fatal(err)
	}
	got, ok, err := LoadCachedPack(root, CorePack, 1)
	if err != nil || !ok {
		t.Fatalf("cache read: ok=%v err=%v", ok, err)
	}
	if len(got.Templates) != len(core.Templates) {
		t.Fatalf("cache holds %d Templates, want %d", len(got.Templates), len(core.Templates))
	}

	pack := t.TempDir()
	write(t, filepath.Join(pack, "pack.aw"), "pack p requires andara.core@1\n")
	write(t, filepath.Join(pack, "t.aw"), "template Merchant extends andara.core.Npc {}\n")
	if out, ds := Compile(pack, got, nil); out == nil {
		t.Fatalf("offline compile failed: %v", ds)
	}

	// No cache: the finding names both versions and the command to run.
	_, ds := Compile(pack, nil, nil)
	if len(ds) != 1 || ds[0].Code != CodeCoreVersionMismatch {
		t.Fatalf("want one core_version_mismatch, got %v", ds)
	}
	if !strings.Contains(ds[0].Message, "fetch-core") {
		t.Errorf("the message does not say what to run: %q", ds[0].Message)
	}
}

// TestCoreVersionMismatchNamesBoth is AC-6, in its own numbers: a pack
// declaring `requires andara.core@4` against a cache of @3.
func TestCoreVersionMismatchNamesBoth(t *testing.T) {
	cached := corpusCore(t)
	cached.Version = 3

	pack := t.TempDir()
	write(t, filepath.Join(pack, "pack.aw"), "pack p requires andara.core@4\n")

	_, ds := Compile(pack, cached, nil)
	if len(ds) != 1 || ds[0].Code != CodeCoreVersionMismatch {
		t.Fatalf("want core_version_mismatch, got %v", ds)
	}
	if !strings.Contains(ds[0].Message, "@4") || !strings.Contains(ds[0].Message, "@3") {
		t.Errorf("the finding must name both versions; it says %q", ds[0].Message)
	}
	// AC-5's cached case, from the other side: @3 required against @3 compiles.
	write(t, filepath.Join(pack, "pack.aw"), "pack p requires andara.core@3\n")
	if out, ds := Compile(pack, cached, nil); out == nil {
		t.Errorf("a matching cache did not satisfy the requirement: %v", ds)
	}
}

