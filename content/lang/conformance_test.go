// corpusDir is the AW-CLI-005 conformance corpus. The tests here are the same
// check `make content-conformance` runs; it is in `make test` as well so that a
// change to the compiler fails on the developer's machine at the same moment it
// would fail in CI.
const corpusDir = "../../docs/specs/content-language/v1/corpus"

// TestConformance is AC-1. Every valid pair matches byte for byte, every
// invalid pair matches its .errors sidecar, and the round-trip pairs are
// identity.
func TestConformance(t *testing.T) {
	rep, err := Conformance(corpusDir)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range rep.Cases {
		if c.OK || c.Skipped {
			continue
		}
		t.Errorf("%s:\n  %s", c.Case, strings.Join(c.Reasons, "\n  "))
	}
	if rep.Passed == 0 {
		t.Fatal("no cases ran; the corpus path is wrong")
	}
	t.Logf("%d cases pass, %d skipped as pending", rep.Passed, rep.Skipped)
}

// TestConformanceIsNotVacuous breaks the compiler and asserts the corpus
// notices. A conformance suite that cannot be made to fail has not been shown
// to check anything, and this one compares generated bytes against hand-written
// ones — exactly the shape that passes for the wrong reason when the comparison
// is misrouted.
func TestConformanceIsNotVacuous(t *testing.T) {
	out, ds := Compile(filepath.Join(corpusDir, "valid", "merge-three-deep"), corpusCore(t), nil)
	if out == nil {
		t.Fatalf("expected a compile: %v", ds)
	}
	beast := templateNamed(t, out, "p.Beast")

	// Beast inherits Behavior.name from Creature and declares Memory itself.
	// Dropping the inherited Component is the merge bug the case exists to
	// catch, so the expected bytes must stop matching when it is dropped.
	before := string(CanonicalJSON(beast))
	beast.Components = beast.Components[1:]
	if after := string(CanonicalJSON(beast)); after == before {
		t.Fatal("dropping a merged Component changed no bytes; the comparison is not reading the Components")
	}
	if !strings.Contains(before, "andara.core.Behavior") {
		t.Error("p.Beast does not carry the Component it inherits from p.Creature")
	}
}

// TestCoreSeedIsReproducible is the first of the corpus's two anchors: the
// compiler's output for corpus/valid/core/ is byte-identical to the shipped
// andara.core seed, which TestCoreSeedMatchesFixture holds from the other side.
// It is what stops the corpus from being a description of whatever its author
// imagined.
func TestCoreSeedIsReproducible(t *testing.T) {
	out, ds := Compile(filepath.Join(corpusDir, "valid", "core"), nil, nil)
	if out == nil {
		t.Fatalf("corpus/valid/core does not compile: %v", ds)
	}
	if len(out.Templates) != 4 {
		t.Fatalf("got %d Templates, want 4", len(out.Templates))
	}
	for _, tmpl := range out.Templates {
		want, err := os.ReadFile(filepath.Join("../core/templates", tmpl.GetName()+".json"))
		if err != nil {
			t.Fatal(err)
		}
		if got := CanonicalJSON(tmpl); string(got) != string(want) {
			t.Errorf("%s differs from the shipped seed:\n--- got ---\n%s\n--- want ---\n%s", tmpl.GetName(), got, want)
		}
	}
}

