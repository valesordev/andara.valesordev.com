class BrokerBreaks(unittest.TestCase):
    """AW-INF-056 AC-8 and AC-14: the broker manifest and the chart values against the declaration."""

    KAFKA = {"kind": "Kafka", "spec": {"kafka": {
        "listeners": [{"name": "scram", "port": 9092, "authentication": {"type": "scram-sha-512"}}],
        "authorization": {"type": "simple", "superUsers": ["andara-operator"]}}}}

    def errors(self, doc=REAL, kafka=None, values=None):
        return kafka_users.check_broker(doc, kafka=copy.deepcopy(kafka or self.KAFKA),
                                        values=values if values is not None else {"values/dev.yaml": "kafkaCreds: andara-server-dev"},
                                        kafka_path="deploy/k8s/kafka/kafka.yaml")

    def assertFails(self, needle, **kw):
        errs = self.errors(**kw)
        self.assertTrue([e for e in errs if needle in e], errs)

    def test_the_fixture_passes(self):
        self.assertEqual(self.errors(), [])

    def test_a_plain_listener_fails_naming_the_file(self):
        kafka = copy.deepcopy(self.KAFKA)
        kafka["spec"]["kafka"]["listeners"].append({"name": "plain", "port": 9094, "tls": False})
        self.assertFails("deploy/k8s/kafka/kafka.yaml: listener plain has no authentication", kafka=kafka)

    def test_no_authorizer_fails(self):
        kafka = copy.deepcopy(self.KAFKA)
        del kafka["spec"]["kafka"]["authorization"]
        self.assertFails("deploy/k8s/kafka/kafka.yaml: authorization is not `simple`", kafka=kafka)

    def test_a_second_superuser_on_the_broker_fails(self):
        kafka = copy.deepcopy(self.KAFKA)
        kafka["spec"]["kafka"]["authorization"]["superUsers"].append("ANONYMOUS")
        self.assertFails("superUsers are ['andara-operator', 'ANONYMOUS'], the declaration's are ['andara-operator']",
                         kafka=kafka)

    def test_a_second_superuser_in_the_declaration_fails(self):
        doc = copy.deepcopy(REAL)
        next(p for p in doc["platform_principals"] if p["name"] == "andara-schema-registry")["superuser"] = True
        self.assertFails("exactly one superuser, andara-operator; the declaration has andara-operator, andara-schema-registry",
                         doc=doc)

    def test_a_superuser_with_acls_fails(self):
        doc = copy.deepcopy(REAL)
        next(p for p in doc["platform_principals"] if p["name"] == "andara-operator")["topics"] = {"_schemas": ["Read"]}
        self.assertFails("andara-operator: a superuser declares no ACLs", doc=doc)

    def test_a_chart_value_naming_the_operators_secret_fails(self):
        self.assertFails("values/dev.yaml: names andara-operator, whose Secret no workload mounts",
                         values={"values/dev.yaml": "kafkaCreds:\n  secretName: andara-operator\n"})

    def test_the_real_values_files_are_read(self):
        self.assertTrue([p for p in kafka_users.values_files() if p.endswith("values/dev.yaml")])
        self.assertTrue([p for p in kafka_users.values_files() if p.endswith("andara/values.yaml")])


class BrokerMetrics(unittest.TestCase):
    """AW-INF-056 Observability: the allow-list keeps the failed-authentication and throttle-time
    families, and a kept throttle series can't carry an unbounded client_id: every quota is a
    KafkaUser's, a user-entity quota, whose series Kafka labels client_id="" (measured on the SASL
    broker, 2026-10-25: kafka_server_produce_throttle_time{client_id="",user="andara-server-local"})."""

    USER_QUOTA_FIELDS = {"producerByteRate", "consumerByteRate", "requestPercentage", "controllerMutationRate"}

    def allow_list(self):
        import yaml
        with open(kafka_users.KAFKA) as f:
            kafka = next(d for d in yaml.safe_load_all(f) if d and d.get("kind") == "Kafka")
        return kafka["spec"]["kafka"]["metricsConfig"]["values"]["allowList"]

    def test_the_families_are_kept(self):
        for pattern in ("kafka_server_socket_server_metrics_failed_authentication.*",
                        "kafka_server_produce_throttle_time.*", "kafka_server_fetch_throttle_time.*"):
            self.assertIn(pattern, self.allow_list())

    def test_no_produce_or_fetch_family_beyond_the_quota_time(self):
        # e.g. "kafka_server_produce_.*" would keep per-client series too.
        broad = [p for p in self.allow_list() if p.startswith(("kafka_server_produce", "kafka_server_fetch"))
                 and not p.startswith(("kafka_server_produce_throttle_time", "kafka_server_fetch_throttle_time"))]
        self.assertEqual(broad, [])

    def test_every_quota_is_a_user_quota(self):
        for env, quota in (REAL.get("quotas") or {}).items():
            self.assertIn(env, kafka_users.environments(REAL))
            self.assertLessEqual(set(quota), self.USER_QUOTA_FIELDS, env)
        for u in users_of(REAL):
            self.assertLessEqual(set(u["spec"].get("quotas") or {}), self.USER_QUOTA_FIELDS)
