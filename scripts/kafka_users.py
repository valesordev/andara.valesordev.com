"""Render and check the Strimzi KafkaUsers declared in deploy/kafka/topics.yaml (AW-INF-055).

    scripts/kafka_users.py render    make kafka-users: the manifests, as YAML, on stdout
    scripts/kafka_users.py check     make kafka-users-check, in `make check` (AC-9)
    scripts/kafka_users.py apply     from `make shared-up` (AW-INF-056): apply them in the broker's
                                     namespace, delete a KafkaUser topics.yaml no longer declares,
                                     and wait until each is Ready (its Secret and ACLs written)

One KafkaUser `<principal>-<env>` for every principal in `principals` and every environment
with a prefix (ADR-0011 decision 4, as ADR-0013 decision 6 amends it): `andara-server-dev`,
`andara-projector-state-local`. Its topic ACLs are LITERAL on `<prefix>.<topic>`, its group
ACLs PREFIXED on `<group>-<env>`, and an environment's `quotas` are on each of its principals.
They are rendered and checked here, and applied by AW-INF-056 once the broker has an
authorizer: Strimzi's User Operator writes ACLs through the Admin API, which a broker without
one refuses (ADR-0013 amendment 19).

`check` renders them and fails, naming the KafkaUser and the ACL, when:
  - a principal holds Create, Alter, AlterConfigs, Delete or All on a topic, or anything but
    Describe on the cluster: topics are the operator's alone (ADR-0011). The one exception is
    the integration suite's `andara-it` (AW-INF-060), which may hold Create and Delete on the
    PREFIXED topics `andara.test.` and `it` (ADR-0013 amendment 17); the exception is by that
    exact name, so no other principal can borrow it. `andara-it` is scoped positively too: its
    topics are those two PREFIXED names only and its groups PREFIXED `it-` only (Delete
    included), so it never reaches an environment's topics or groups;
  - a principal holds Delete on a group other than andara-projector-state's own
    (`andara-projector --rebuild` deletes it);
  - a topic or group ACL names a literal `*`, or reaches outside its environment: a topic not
    under `<prefix>.`, or a group not ending `-<env>`;
  - a declared principal has no KafkaUser in some environment, or one environment's
    principals carry another's quotas (dev's have none);
  - a principal's topic is not one the declaration's `topics` names.

Platform principals (`platform_principals`, AW-INF-057) are rendered once, as `<name>` with the
label andara.valesor/scope=platform and no environment, and checked on their own: every topic ACL
LITERAL on a declared platform topic (never an environment's), every group ACL LITERAL, no
wildcard, nothing the operator alone may do (Create, Alter, AlterConfigs, Delete, All), no
cluster ACL, and no name an environment principal uses. The schema registry has two exceptions,
each by exact principal and name, both what Karapace needs on the SASL broker (AW-INF-056): Create
on `_schemas` (its reader sends CreateTopics at every start and reads only on TopicAlreadyExists),
and Read on the PREFIXED group `karapace-autogenerated-` (its reader's group id is that and a
random suffix, `prefixed_groups` in topics.yaml). One of them is the superuser
(`superuser: true`): a SCRAM credential and no ACLs, its rights the broker's `superUsers`.

`check` also reads deploy/k8s/kafka/kafka.yaml and the chart's values files (AW-INF-056), and
fails, naming the file, when: a listener has no authentication (a `plain` listener, AC-8); the
broker's authorization is not `simple`; the declaration does not have exactly one superuser,
andara-operator, or it declares ACLs, or the broker's `superUsers` differ from it (AC-14); or a
values file names andara-operator, whose Secret no workload mounts (AC-14).

Exit codes: 0 ok; 1 a check or an apply failed; 2 usage; 3 the cluster context is missing.
"""

import glob
import os
import subprocess
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kube  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECL = os.path.join(REPO, "deploy", "kafka", "topics.yaml")
KAFKA = os.path.join(REPO, "deploy", "k8s", "kafka", "kafka.yaml")
SUPERUSER = "andara-operator"
CLUSTER = "andara-log"
API = "kafka.strimzi.io/v1"
ENV_LABEL = "andara.valesor/env"

TOPIC_FORBIDDEN = {"Create", "Alter", "AlterConfigs", "Delete", "All"}
CLUSTER_ALLOWED = {"Describe"}
IT_PRINCIPAL = "andara-it"
IT_PREFIXES = {"andara.test.", "it"}
IT_ALLOWED = {"Create", "Delete"}
IT_GROUP_PREFIX = "it-"
GROUP_DELETER = "andara-projector-state"
SCOPE_LABEL = "andara.valesor/scope"
PLATFORM = "platform"
GROUP_FORBIDDEN = {"All", "Alter", "AlterConfigs", "Create", "Delete"}
REGISTRY = "andara-schema-registry"
REGISTRY_TOPIC_CREATE = "_schemas"
REGISTRY_READER_GROUPS = "karapace-autogenerated-"


def load(path=DECL):
    with open(path) as f:
        return yaml.safe_load(f)


def environments(doc):
    """{env: prefix} for every environment with a prefix: the ones the shared broker serves."""
    return {env: str(e.get("prefix") or "") for env, e in (doc.get("environments") or {}).items()
            if e.get("prefix")}


def render(doc):
    users = []
    quotas = doc.get("quotas") or {}
    for env, prefix in environments(doc).items():
        for p in doc.get("principals") or []:
            acls = [{"resource": {"type": "topic", "name": "%s.%s" % (prefix, topic), "patternType": "literal"},
                     "operations": list(ops)}
                    for topic, ops in (p.get("topics") or {}).items()]
            acls += [{"resource": {"type": "group", "name": "%s-%s" % (group, env), "patternType": "prefix"},
                      "operations": list(ops)}
                     for group, ops in (p.get("groups") or {}).items()]
            if p.get("cluster"):
                acls.append({"resource": {"type": "cluster"}, "operations": list(p["cluster"])})
            spec = {"authentication": {"type": "scram-sha-512"},
                    "authorization": {"type": "simple", "acls": acls}}
            if env in quotas:
                spec["quotas"] = dict(quotas[env])
            users.append({
                "apiVersion": API,
                "kind": "KafkaUser",
                "metadata": {"name": "%s-%s" % (p["name"], env),
                             "labels": {"strimzi.io/cluster": CLUSTER, ENV_LABEL: env}},
                "spec": spec,
            })
    for p in doc.get("platform_principals") or []:
        if p.get("superuser"):
            users.append({
                "apiVersion": API,
                "kind": "KafkaUser",
                "metadata": {"name": p["name"], "labels": {"strimzi.io/cluster": CLUSTER, SCOPE_LABEL: PLATFORM}},
                "spec": {"authentication": {"type": "scram-sha-512"}},
            })
            continue
        acls = [{"resource": {"type": "topic", "name": topic, "patternType": "literal"}, "operations": list(ops)}
                for topic, ops in (p.get("topics") or {}).items()]
        acls += [{"resource": {"type": "group", "name": group, "patternType": "literal"}, "operations": list(ops)}
                 for group, ops in (p.get("groups") or {}).items()]
        acls += [{"resource": {"type": "group", "name": group, "patternType": "prefix"}, "operations": list(ops)}
                 for group, ops in (p.get("prefixed_groups") or {}).items()]
        users.append({
            "apiVersion": API,
            "kind": "KafkaUser",
            "metadata": {"name": p["name"], "labels": {"strimzi.io/cluster": CLUSTER, SCOPE_LABEL: PLATFORM}},
            "spec": {"authentication": {"type": "scram-sha-512"},
                     "authorization": {"type": "simple", "acls": acls}},
        })
    return users


def platform(user):
    return user["metadata"].get("labels", {}).get(SCOPE_LABEL) == PLATFORM


def check_platform(users, doc):
    """Platform principals: LITERAL ACLs on declared platform topics and their own groups only."""
    errors = []
    platform_topics = {t["name"] for t in doc.get("platform_topics") or []}
    env_names = {p["name"] for p in doc.get("principals") or []}
    for u in users:
        name = u["metadata"]["name"]
        if name in env_names or name == IT_PRINCIPAL:
            errors.append("%s: a platform principal can't share an environment principal's name" % name)
        for acl in (u.get("spec", {}).get("authorization") or {}).get("acls") or []:
            r = acl.get("resource", {})
            rtype, rname, pattern = r.get("type"), str(r.get("name", "")), r.get("patternType", "literal")
            ops = set(acl.get("operations") or [])
            what = "%s: %s %s %s %s" % (name, rtype, pattern, rname or "-", ",".join(sorted(ops)))
            # The registry's Create on _schemas is the one exception to the operator's topic rights.
            forbidden = TOPIC_FORBIDDEN - ({"Create"} if (name, rname) == (REGISTRY, REGISTRY_TOPIC_CREATE) else set())
            if rtype not in ("topic", "group"):
                errors.append("%s: a platform principal holds no %s ACL" % (what, rtype))
            elif "*" in rname:
                errors.append("%s: a wildcard name" % what)
            elif pattern != "literal" and not (name == REGISTRY and rtype == "group"
                                               and pattern == "prefix" and rname == REGISTRY_READER_GROUPS):
                errors.append("%s: a platform principal's ACLs are LITERAL" % what)
            elif rtype == "topic" and rname not in platform_topics:
                errors.append("%s: not a declared platform topic" % what)
            elif rtype == "topic" and ops & forbidden:
                errors.append("%s: %s on a topic is the operator's alone" % (what, ",".join(sorted(ops & forbidden))))
            elif rtype == "group" and ops & GROUP_FORBIDDEN:
                errors.append("%s: %s on a group" % (what, ",".join(sorted(ops & GROUP_FORBIDDEN))))
    return errors


def principal_of(user):
    """(principal, env) of a rendered KafkaUser, from its name and label."""
    env = user["metadata"].get("labels", {}).get(ENV_LABEL, "")
    name = user["metadata"]["name"]
    if env and name.endswith("-" + env):
        return name[:-len(env) - 1], env
    return name, env


def check(users, doc):
    errors = []
    envs = environments(doc)
    quotas = doc.get("quotas") or {}
    declared = {p["name"] for p in doc.get("principals") or []}
    topic_names = {t["name"] for t in doc.get("topics") or []}
    for p in doc.get("principals") or []:
        for topic in sorted(set(p.get("topics") or {}) - topic_names):
            errors.append("%s: an ACL on %s, which the declaration's topics don't name" % (p["name"], topic))
    errors += check_platform([u for u in users if platform(u)], doc)
    users = [u for u in users if not platform(u)]
    seen = set()
    for u in users:
        name = u["metadata"]["name"]
        principal, env = principal_of(u)
        seen.add((principal, env))
        prefix = envs.get(env)
        for acl in (u.get("spec", {}).get("authorization") or {}).get("acls") or []:
            r = acl.get("resource", {})
            rtype, rname, pattern = r.get("type"), str(r.get("name", "")), r.get("patternType", "literal")
            ops = set(acl.get("operations") or [])
            what = "%s: %s %s %s %s" % (name, rtype, pattern, rname or "-", ",".join(sorted(ops)))
            if rtype in ("topic", "group") and (rname == "*" or "*" in rname):
                errors.append("%s: a wildcard name" % what)
                continue
            it = name == IT_PRINCIPAL
            if rtype == "topic":
                bad = ops & TOPIC_FORBIDDEN
                in_suite = pattern == "prefix" and rname in IT_PREFIXES
                if it and in_suite:
                    bad -= IT_ALLOWED
                if bad:
                    errors.append("%s: %s on a topic is the operator's alone" % (what, ",".join(sorted(bad))))
                if it and not in_suite:
                    # The suite never touches an environment's data (ADR-0013 amendment 17).
                    errors.append("%s: %s's topics are PREFIXED %s only" % (what, IT_PRINCIPAL,
                                                                           " and ".join(sorted(IT_PREFIXES))))
                if not it and (prefix is None or not rname.startswith(prefix + ".")):
                    errors.append("%s: outside environment %s's prefix %s." % (what, env or "(none)", prefix))
            elif rtype == "group":
                own = (principal == GROUP_DELETER and rname == "%s-%s" % (GROUP_DELETER, env)) \
                    or (it and pattern == "prefix" and rname.startswith(IT_GROUP_PREFIX))
                if "Delete" in ops and not own:
                    errors.append("%s: Delete on a group other than %s-<env>'s own" % (what, GROUP_DELETER))
                if ops & {"All", "Alter", "AlterConfigs", "Create"}:
                    errors.append("%s: %s on a group" % (what, ",".join(sorted(ops & {"All", "Alter", "AlterConfigs", "Create"}))))
                if it and not (pattern == "prefix" and rname.startswith(IT_GROUP_PREFIX)):
                    # A principal that can join andara-sim-dev can move dev's offsets.
                    errors.append("%s: %s's groups are PREFIXED %s only" % (what, IT_PRINCIPAL, IT_GROUP_PREFIX))
                if not it and not rname.endswith("-" + env):
                    errors.append("%s: a group outside environment %s" % (what, env or "(none)"))
            elif rtype == "cluster":
                if ops - CLUSTER_ALLOWED:
                    errors.append("%s: %s on the cluster" % (what, ",".join(sorted(ops - CLUSTER_ALLOWED))))
            else:
                errors.append("%s: an ACL on a %s" % (what, rtype))
        want = quotas.get(env)
        have = u.get("spec", {}).get("quotas")
        if name != IT_PRINCIPAL and have != want:
            errors.append("%s: quotas %r, environment %s declares %r" % (name, have, env, want))
    for env in envs:
        for principal in sorted(declared):
            if (principal, env) not in seen:
                errors.append("%s-%s: no KafkaUser for principal %s in environment %s"
                              % (principal, env, principal, env))
    return errors


def superusers(doc):
    return [p["name"] for p in doc.get("platform_principals") or [] if p.get("superuser")]


def values_files():
    return [os.path.join(REPO, "deploy", "helm", "andara", "values.yaml")] + \
        sorted(glob.glob(os.path.join(REPO, "deploy", "helm", "values", "*.yaml")))


def check_broker(doc, kafka=None, values=None, kafka_path=None):
    """The broker manifest and the chart values against the declaration's superuser (AW-INF-056)."""
    errors = []
    if kafka is None:
        kafka_path = os.path.relpath(KAFKA, REPO)
        with open(KAFKA) as f:
            kafka = next(d for d in yaml.safe_load_all(f) if d and d.get("kind") == "Kafka")
    if values is None:
        values = {}
        for path in values_files():
            with open(path) as f:
                values[os.path.relpath(path, REPO)] = f.read()
    spec = kafka.get("spec", {}).get("kafka", {})
    for listener in spec.get("listeners") or []:
        if not listener.get("authentication"):
            errors.append("%s: listener %s has no authentication; every client authenticates (ADR-0011)"
                          % (kafka_path, listener.get("name")))
    auth = spec.get("authorization") or {}
    if auth.get("type") != "simple":
        errors.append("%s: authorization is not `simple`; the broker denies by default (ADR-0011)" % kafka_path)
    declared = superusers(doc)
    if declared != [SUPERUSER]:
        errors.append("topics.yaml: exactly one superuser, %s; the declaration has %s"
                      % (SUPERUSER, ", ".join(declared) or "none"))
    for p in doc.get("platform_principals") or []:
        if p.get("superuser") and (p.get("topics") or p.get("groups") or p.get("cluster")):
            errors.append("topics.yaml: %s: a superuser declares no ACLs; its rights are the broker's superUsers"
                          % p["name"])
    if auth and list(auth.get("superUsers") or []) != declared:
        errors.append("%s: superUsers are %s, the declaration's are %s"
                      % (kafka_path, list(auth.get("superUsers") or []), declared))
    for path, text in sorted(values.items()):
        if SUPERUSER in text:
            errors.append("%s: names %s, whose Secret no workload mounts" % (path, SUPERUSER))
    return errors


READY_TIMEOUT = "300s"


def apply(ns, users, run=subprocess.run):
    """Apply the rendered KafkaUsers in ns, delete the undeclared ones, wait for each to be Ready."""
    def kubectl(*args, input=None):
        p = run(kube.kubectl("-n", ns, *args), capture_output=True, text=True, input=input)
        if p.returncode != 0:
            print("make: kafka-users: kubectl %s: %s" % (" ".join(args[:3]), (p.stderr or p.stdout).strip()),
                  file=sys.stderr)
            sys.exit(1)
        return p.stdout
    out = kubectl("apply", "-f", "-", input=yaml.safe_dump_all(users, sort_keys=False))
    for line in out.splitlines():
        print("shared: %s" % line.strip())
    want = {u["metadata"]["name"] for u in users}
    live = kubectl("get", "kafkausers", "-l", "strimzi.io/cluster=" + CLUSTER, "-o", "name").split()
    for res in sorted(live):
        name = res.split("/", 1)[1]
        if name not in want:
            kubectl("delete", res)
            print("shared: deleted KafkaUser %s: topics.yaml no longer declares it" % name)
    for name in sorted(want):
        kubectl("wait", "kafkauser/" + name, "--for=condition=Ready", "--timeout=" + READY_TIMEOUT)
    print("shared: %d KafkaUser(s) Ready in %s, each with its Secret and ACLs" % (len(want), ns))


def main(argv):
    if argv not in (["render"], ["check"], ["apply"]):
        print("usage: scripts/kafka_users.py render | check | apply", file=sys.stderr)
        return 2
    doc = load()
    users = render(doc)
    if argv == ["apply"]:
        apply(os.environ.get("ANDARA_KAFKA_NAMESPACE", "andara-shared"), users)
        return 0
    if argv == ["render"]:
        sys.stdout.write(yaml.safe_dump_all(users, sort_keys=False))
        return 0
    errors = check(users, doc) + check_broker(doc)
    for e in errors:
        print("kafka-users-check: %s" % e, file=sys.stderr)
    if errors:
        print("make: kafka-users-check: %d finding(s) in the KafkaUsers rendered from deploy/kafka/topics.yaml"
              % len(errors), file=sys.stderr)
        return 1
    n_platform = len([u for u in users if platform(u)])
    print("kafka-users-check: %d KafkaUsers across %s, each scoped to its prefix, and %d platform principal(s)"
          % (len(users) - n_platform, ", ".join(sorted(environments(doc))), n_platform))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
